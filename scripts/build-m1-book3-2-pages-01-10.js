function sum(arr, key) {
  return arr.reduce((a, r) => a + (Number(r[key]) || 0), 0);
}

function pageBreakdown(rows, amountKey) {
  const m = {};
  for (const r of rows) {
    if (!m[r.page]) m[r.page] = { count: 0, total: 0 };
    m[r.page].count++;
    m[r.page].total += Number(r[amountKey]) || 0;
  }
  return m;
}

