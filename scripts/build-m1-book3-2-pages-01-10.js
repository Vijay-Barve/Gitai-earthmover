const incRecv = sum(income, 'received');
const incPend = sum(income, 'pending');
const expTotal = sum(expense, 'amount');

const incByPage = pageBreakdown(income, 'bill');
const expByPage = pageBreakdown(expense, 'amount');
const incRecvByPage = pageBreakdown(income, 'received');
const incPendByPage = pageBreakdown(income, 'pending');

