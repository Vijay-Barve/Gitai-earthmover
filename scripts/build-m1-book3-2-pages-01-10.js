function parseHours(work) {
  if (!work) return 0;
  const s = String(work);
  let h = 0;
  const hm = s.match(/(\d+(?:\.\d+)?)\s*(?:ता|तास)/);
  if (hm) h += Number(hm[1]);
  const trip = s.match(/(\d+)\s*ट्र/i);
  if (trip && !hm) h += 0;
  const mm = s.match(/(\d+)\s*मि/);
  if (mm) h += Number(mm[1]) / 60;
  const dec = s.match(/^(\d+\.\d+)\s*$/);
  if (dec && !hm) h += Number(dec[1]);
  return Math.round(h * 100) / 100;
}

function inc(page, customer, work, bill, received, pending, remarks = '') {
  return {
    page,
    date: '',
    customer,
    work,
    hours: parseHours(work),
    bill,
    received,
    pending,
    remarks
  };
}

function incFull(page, date, customer, work, bill, received, pending, remarks = '') {
  return { page, date, customer, work, hours: parseHours(work), bill, received, pending, remarks };
}

function exp(page, date, expenseType, description, amount, remarks = '') {
  return { page, date, expenseType, description, amount, paidBy: '', remarks };
}

